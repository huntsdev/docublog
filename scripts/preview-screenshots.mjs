import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
await page.goto('http://127.0.0.1:4322/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/home-light.png', fullPage: true });
await page.evaluate(() => { localStorage.setItem('hunts-theme', 'dark'); });
await page.reload({ waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/home-dark.png', fullPage: true });
await page.getByRole('button', { name: 'Search all posts, projects, and pages' }).click();
await page.getByRole('combobox', { name: 'Search the site' }).fill('Active Directory');
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/search.png' });
await page.keyboard.press('Escape');
await page.evaluate(() => { localStorage.setItem('hunts-theme', 'light'); });
await page.goto('http://127.0.0.1:4322/blog/active-directory-enumeration/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/article.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:4322/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
await browser.close();
console.log('Saved light, dark, search, article, and mobile screenshots under artifacts/.');
